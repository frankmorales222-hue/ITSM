def read_env_file(path: Path) -> dict[str, str]:
    """Read simple KEY=VALUE settings from a Northstar .env file."""
    values: dict[str, str] = {}
    if not path.is_file():
        raise RuntimeError(f"Configuration file was not found: {path}")
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        value = value.strip()
        if len(value) >= 2 and value[0] == '"' and value[-1] == '"':
            value = value[1:-1].replace('\\"', '"')
        values[key.strip()] = value
    return values


GENERATED_PRODUCTION_KEYS = {
    "ITSM_ALLOWED_ORIGINS",
    "ITSM_BACKUP_DIRECTORY",
    "ITSM_BIND_HOST",
    "ITSM_COOKIE_SECURE",
    "ITSM_DATABASE_URL",
    "ITSM_DATA_DIRECTORY",
    "ITSM_ENVIRONMENT",
    "ITSM_FORWARDED_ALLOW_IPS",
    "ITSM_HTTPS_PORT",
    "ITSM_PORT",
    "ITSM_PUBLIC_URL",
    "ITSM_TRUSTED_HOSTS",
    "ITSM_UPDATE_STAGING_DIRECTORY",
}

LOCAL_MACHINE_PATH_KEYS = {
    "ITSM_ASSETPILOT_DATABASE_PATH",
    "ITSM_ASSETPILOT_EXECUTABLE",
}


def imported_production_settings(source_env: Path | None) -> dict[str, str]:
    """Return safe old-server settings to merge into a new-server config.

    The old database URL and machine-local paths are deliberately ignored so a
    restored server never points back at the retired machine.  ``ITSM_SECRET_KEY``
    is preserved because database-stored integration credentials are encrypted
    with it.
    """
    if source_env is None:
        return {}
    source_values = read_env_file(source_env)
    imported: dict[str, str] = {}
    for key, value in source_values.items():
        if not key.startswith("ITSM_"):
            continue
        if key in GENERATED_PRODUCTION_KEYS or key in LOCAL_MACHINE_PATH_KEYS:
            continue
        imported[key] = value
    return imported


def write_production_config(
    data_root: Path,
    organization: str,
    dns_name: str,
    asset_dns_name: str,
    database_host: str,
    database_port: int,
    database_name: str,
    database_user: str,
    database_password: str,
    backup_directory: Path,
    https_port: int = 443,
    northstar_port: int = 8000,
    assetpilot_port: int = 5080,
    source_env: Path | None = None,
) -> None:
    """Create the protected server configuration and pilot HTTPS proxy file."""
    data_root.mkdir(parents=True, exist_ok=True)
    backup_directory.mkdir(parents=True, exist_ok=True)
    imported_settings = imported_production_settings(source_env)
    secret_key = imported_settings.pop("ITSM_SECRET_KEY", secrets.token_urlsafe(48))
    encoded_user = quote(database_user, safe="")
    encoded_password = quote(database_password, safe="")
    database_url = (
        f"postgresql+psycopg://{encoded_user}:{encoded_password}@"
        f"{database_host}:{database_port}/{database_name}"
    )
    validate_service_ports(https_port, northstar_port, assetpilot_port)
    public_url = https_url(dns_name, https_port)
    lines = [
        "ITSM_ENVIRONMENT=production",
        f"ITSM_DATABASE_URL={quote_env(database_url)}",
        f"ITSM_SECRET_KEY={secret_key}",
        "ITSM_SESSION_MINUTES=480",
        "ITSM_COOKIE_SECURE=true",
        f"ITSM_PUBLIC_URL={public_url}",
        f"ITSM_ALLOWED_ORIGINS={public_url}",
        f"ITSM_TRUSTED_HOSTS={dns_name}",
        "ITSM_FORWARDED_ALLOW_IPS=127.0.0.1",
        "ITSM_BIND_HOST=127.0.0.1",
        f"ITSM_PORT={northstar_port}",
        f"ITSM_HTTPS_PORT={https_port}",
        "ITSM_OUTBOUND_EMAIL_ENABLED=false",
        "ITSM_ASSETPILOT_ENABLED=false",
        f"ITSM_DATA_DIRECTORY={quote_env(str(data_root / 'data'))}",
        f"ITSM_BACKUP_DIRECTORY={quote_env(str(backup_directory))}",
        f"ITSM_SITE_NAME={quote_env(organization or 'Northstar Desk')}",
        "ITSM_AGENT_ALLOW_ACCOUNT_NAME_MATCH=true",
        f"ITSM_UPDATE_STAGING_DIRECTORY={quote_env(str(data_root / 'updates'))}",
    ]
    existing_keys = {line.split("=", 1)[0] for line in lines if "=" in line}
    for key in sorted(imported_settings):
        if key not in existing_keys:
            lines.append(f"{key}={quote_env(imported_settings[key])}")
    update_public_key = installed_update_public_key()
    if update_public_key:
        lines.append(f"ITSM_UPDATE_PUBLIC_KEY={update_public_key}")
    target = config_path(data_root)
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    write_caddy_config(
        data_root, dns_name, asset_dns_name, https_port, northstar_port, assetpilot_port,
    )


def _replace_keyed_lines(path: Path, replacements: dict[str, str]) -> None:
    lines = path.read_text(encoding="utf-8").splitlines()
    remaining = dict(replacements)
    result: list[str] = []
    for line in lines:
        matched = next((key for key in remaining if line.startswith(key)), None)
        if matched is None:
            result.append(line)
        else:
            result.append(remaining.pop(matched))
    result.extend(remaining.values())
    path.write_text("\n".join(result) + "\n", encoding="utf-8")


def configure_service_ports(
    data_root: Path,
    https_port: int,
    northstar_port: int,
    assetpilot_port: int,
    dns_name: str | None = None,
    asset_dns_name: str | None = None,
) -> None:
    """Change service addresses without rotating credentials or other settings."""
    validate_service_ports(https_port, northstar_port, assetpilot_port)
    target = config_path(data_root)
    if not target.is_file():
        raise RuntimeError("Northstar Desk must be configured before its ports can be changed.")
    values: dict[str, str] = {}
    for line in target.read_text(encoding="utf-8").splitlines():
        if "=" not in line or line.lstrip().startswith("#"):
            continue
        key, value = line.split("=", 1)
        values[key] = value.strip().strip('"')
    northstar_host = dns_name or urlsplit(values.get("ITSM_PUBLIC_URL", "")).hostname
    assetpilot_host = asset_dns_name or "assets.invalid"
    if not northstar_host:
        raise RuntimeError("The existing Northstar Desk DNS name could not be read.")
    public_url = https_url(northstar_host, https_port)
    _replace_keyed_lines(target, {
        "ITSM_PUBLIC_URL=": f"ITSM_PUBLIC_URL={public_url}",
        "ITSM_ALLOWED_ORIGINS=": f"ITSM_ALLOWED_ORIGINS={public_url}",
        "ITSM_TRUSTED_HOSTS=": f"ITSM_TRUSTED_HOSTS={northstar_host}",
        "ITSM_PORT=": f"ITSM_PORT={northstar_port}",
        "ITSM_HTTPS_PORT=": f"ITSM_HTTPS_PORT={https_port}",
    })
    write_caddy_config(
        data_root, northstar_host, assetpilot_host,
        https_port, northstar_port, assetpilot_port,
    )
    print(
        f"Service ports configured: HTTPS {https_port}, Northstar Desk {northstar_port}."
    )


def protect_production_secrets(data_root: Path) -> None:
    """Lock production secrets only after initialization has consumed them.

    Applying these ACLs before Alembic/Pydantic re-read ``.env`` caused the
    packaged configuration command to deny itself access when launched outside
    a SYSTEM token.  The scheduled services run as SYSTEM, so protecting the
    files after successful initialization preserves both usability and the
    intended least-access production posture.
    """
    if os.name != "nt":
        return
    for target in (
        config_path(data_root),
    ):
        if not target.exists():
            continue
        subprocess.run(
            ["icacls.exe", str(target), "/inheritance:r", "/grant:r",
             "Administrators:(F)", "SYSTEM:(F)"],
            check=True,
            stdout=subprocess.DEVNULL,
        )


def provision_postgresql(
    host: str,
    port: int,
    database_name: str,
    service_user: str,
    admin_user: str,
    admin_password: str,
) -> str:
    """Create or repair the least-privilege application role and database."""
    import psycopg
    from psycopg import sql

    service_password = secrets.token_urlsafe(36)
    with psycopg.connect(
        host=host,
        port=port,
        dbname="postgres",
        user=admin_user,
        password=admin_password,
        autocommit=True,
        connect_timeout=10,
    ) as connection:
        role_exists = connection.execute(
            "SELECT 1 FROM pg_roles WHERE rolname = %s", (service_user,)
        ).fetchone()
        if role_exists:
            connection.execute(
                sql.SQL("ALTER ROLE {} WITH LOGIN PASSWORD {}").format(
                    sql.Identifier(service_user), sql.Literal(service_password)
                )
            )
        else:
            connection.execute(
                sql.SQL("CREATE ROLE {} WITH LOGIN PASSWORD {}").format(
                    sql.Identifier(service_user), sql.Literal(service_password)
                )
            )
        database_exists = connection.execute(
            "SELECT 1 FROM pg_database WHERE datname = %s", (database_name,)
        ).fetchone()
        if not database_exists:
            connection.execute(
                sql.SQL("CREATE DATABASE {} OWNER {}").format(
                    sql.Identifier(database_name), sql.Identifier(service_user)
                )
            )
        else:
            connection.execute(
                sql.SQL("ALTER DATABASE {} OWNER TO {}").format(
                    sql.Identifier(database_name), sql.Identifier(service_user)
                )
            )
    return service_password


def ensure_alembic_version_capacity(database_url: str) -> None:
    """Repair legacy Alembic tracking columns before running any revision.

    Alembic's default ``version_num`` column is VARCHAR(32), while this
    application's descriptive revision identifiers can be longer.  This
    preflight is deliberately independent of the current revision so it also
    repairs an installation resuming after revision 0006 was already skipped
    or applied by an older build.
    """
    from sqlalchemy import create_engine, inspect, text

    engine = create_engine(database_url, pool_pre_ping=True)
    try:
        with engine.begin() as connection:
            if connection.dialect.name != "postgresql":
                return
            inspector = inspect(connection)
            if "alembic_version" not in inspector.get_table_names():
                return
            version_column = next(
                (column for column in inspector.get_columns("alembic_version")
                 if column["name"] == "version_num"),
                None,
            )
            current_length = getattr(version_column["type"], "length", None) if version_column else None
            if current_length is not None and current_length < 128:
                connection.execute(text(
                    "ALTER TABLE alembic_version "
                    "ALTER COLUMN version_num TYPE VARCHAR(128)"
                ))
    finally:
        engine.dispose()


def initialize(
    data_root: Path,
    organization: str = "",
    admin_email: str = "",
    admin_password: str = "",
) -> None:
    activate(data_root)
    from alembic import command
    from alembic.config import Config
    from sqlalchemy import select
    from itsm.config import settings

    root = bundle_root()
    ensure_alembic_version_capacity(settings.database_url)
    alembic = Config(str(root / "alembic.ini"))
    alembic.set_main_option("script_location", str(root / "migrations"))
    alembic.set_main_option("sqlalchemy.url", settings.database_url.replace("%", "%%"))
    command.upgrade(alembic, "head")
    if settings.production:
        from itsm.seed import seed_production
        seed_production(organization, admin_email, admin_password)
    else:
        from itsm.seed import seed
        seed()
        if organization or admin_email:
            from itsm.database import SessionLocal
            from itsm.models import Organization, Role, User
            with SessionLocal() as db:
                item = db.scalar(select(Organization).order_by(Organization.id))
                if item and organization:
                    item.name = organization
                admin = db.scalar(select(User).where(User.role == Role.ADMIN).order_by(User.id))
                if admin and admin_email:
                    admin.email = admin_email.strip().lower()
                db.commit()


def open_when_ready(url: str) -> None:
    for _ in range(60):
        try:
            with urllib.request.urlopen(url + "/api/health/ready", timeout=1) as response:
                if response.status == 200:
                    webbrowser.open(url)
                    return
        except Exception:
            time.sleep(0.5)


def serve(data_root: Path, open_browser: bool) -> None:
    activate(data_root)
    from itsm.config import settings
    initialize(data_root)
    from itsm.worker import main as worker_main
    from itsm.main import app
    threading.Thread(target=worker_main, name="northstar-worker", daemon=True).start()
    url = settings.public_url.rstrip("/")
    if open_browser:
        threading.Thread(target=open_when_ready, args=(url,), daemon=True).start()
    import uvicorn
    uvicorn.run(app, host=settings.bind_host, port=settings.port,
                proxy_headers=True, forwarded_allow_ips=settings.forwarded_allow_ips, log_level="info")


