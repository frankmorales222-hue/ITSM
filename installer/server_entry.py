def bundle_root() -> Path:
    return Path(getattr(sys, "_MEIPASS", Path(__file__).resolve().parents[1]))


def quote_env(value: str) -> str:
    return '"' + value.replace("\\", "/").replace('"', '\\"') + '"'


def config_path(data_root: Path) -> Path:
    return data_root / ".env"


def validate_service_ports(
    https_port: int, northstar_port: int, assetpilot_port: int | None = None
) -> None:
    ports = {
        "HTTPS": https_port,
        "Northstar Desk": northstar_port,
    }
    for name, port in ports.items():
        if not 1 <= port <= 65535:
            raise ValueError(f"{name} port must be between 1 and 65535")
    if len(set(ports.values())) != len(ports):
        raise ValueError("HTTPS and Northstar Desk must use different ports")


def https_url(hostname: str, port: int) -> str:
    return f"https://{hostname}" if port == 443 else f"https://{hostname}:{port}"


def write_caddy_config(
    data_root: Path,
    dns_name: str,
    asset_dns_name: str,
    https_port: int,
    northstar_port: int,
    assetpilot_port: int,
) -> None:
    northstar_address = dns_name if https_port == 443 else f"https://{dns_name}:{https_port}"
    (data_root / "Caddyfile").write_text(
        f"""# HTTPS configuration generated by Northstar Desk Setup.
# Caddy's local CA root must be trusted by client computers (normally through Group Policy).
{northstar_address} {{
    tls internal
    encode zstd gzip
    reverse_proxy 127.0.0.1:{northstar_port}
    header {{
        Strict-Transport-Security \"max-age=31536000; includeSubDomains\"
        X-Content-Type-Options \"nosniff\"
        Referrer-Policy \"strict-origin-when-cross-origin\"
    }}
}}
""",
        encoding="utf-8",
    )


def installed_update_public_key() -> str:
    candidate = Path(sys.executable).resolve().parent / "update-public-key.txt"
    if not candidate.is_file():
        return ""
    value = candidate.read_text(encoding="ascii").strip()
    try:
        if len(base64.b64decode(value, validate=True)) != 32:
            return ""
    except ValueError:
        return ""
    return value


def configure_update_trust(data_root: Path, public_key_file: Path) -> None:
    value = public_key_file.read_text(encoding="ascii").strip()
    try:
        if len(base64.b64decode(value, validate=True)) != 32:
            raise ValueError("length")
    except ValueError as exc:
        raise RuntimeError("The update verification public key is invalid.") from exc
    target = config_path(data_root)
    if not target.is_file():
        raise RuntimeError("Northstar Desk must be configured before update trust can be installed.")
    lines = [line for line in target.read_text(encoding="utf-8").splitlines()
             if not line.startswith("ITSM_UPDATE_PUBLIC_KEY=") and not line.startswith("ITSM_UPDATE_STAGING_DIRECTORY=")]
    lines.extend([f"ITSM_UPDATE_PUBLIC_KEY={value}",
                  f"ITSM_UPDATE_STAGING_DIRECTORY={quote_env(str(data_root / 'updates'))}"])
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    if os.name == "nt":
        subprocess.run(["icacls.exe", str(target), "/inheritance:r", "/grant:r",
                        "Administrators:(F)", "SYSTEM:(F)"], check=True, stdout=subprocess.DEVNULL)


def activate(data_root: Path) -> None:
    root = bundle_root()
    os.environ["ITSM_CONFIG_FILE"] = str(config_path(data_root))
    os.environ["ITSM_DATA_DIRECTORY"] = str(data_root / "data")
    os.environ["ITSM_STATIC_DIRECTORY"] = str(root / "frontend" / "dist")
    os.chdir(data_root)


