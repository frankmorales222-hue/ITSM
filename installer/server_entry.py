def copy_restored_data_files(source_data_root: Path, target_data_root: Path) -> None:
    """Copy filesystem data that is not contained in the database dump."""
    copied: list[str] = []
    for relative in ("data/attachments",):
        source = source_data_root / relative
        if not source.is_dir():
            continue
        destination = target_data_root / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copytree(source, destination, dirs_exist_ok=True)
        copied.append(relative)
    if copied:
        print("Copied restored data folders: " + ", ".join(copied))


def check_required_ports(https_port: int, northstar_port: int) -> None:
    """Fail before configuration if another product owns a required port."""
    if https_port == northstar_port:
        raise ValueError("HTTPS and Northstar Desk must use different ports")
    listeners: list[socket.socket] = []
    try:
        for host, port in (
            ("127.0.0.1", northstar_port),
            ("0.0.0.0", https_port),
        ):
            listener = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
            if os.name == "nt":
                listener.setsockopt(socket.SOL_SOCKET, socket.SO_EXCLUSIVEADDRUSE, 1)
            try:
                listener.bind((host, port))
            except OSError as exc:
                listener.close()
                raise RuntimeError(
                    f"Required TCP port {port} is already in use ({exc}). "
                    "Stop the conflicting service and run setup again."
                ) from exc
            listeners.append(listener)
    finally:
        for listener in listeners:
            listener.close()
    print(
        f"Required TCP ports {https_port} and {northstar_port} are available."
    )


def internal_health_request(url: str, public_url: str = "") -> urllib.request.Request:
    """Build an internal probe accepted by production TrustedHostMiddleware."""
    public_host = urlsplit(public_url).hostname
    return urllib.request.Request(
        url, headers={"Host": public_host} if public_host else {}
    )


def wait_for_installed_services(data_root: Path, timeout_seconds: int) -> None:
    """Fail setup only when the core Northstar service is not healthy.

    AssetPilot is an optional integration and must never prevent the service
    desk from installing, starting, authenticating users, or processing work.
    """
    activate(data_root)
    from alembic.config import Config
    from alembic.script import ScriptDirectory
    from sqlalchemy import create_engine, text
    from itsm.config import settings

    root = bundle_root()
    alembic = Config(str(root / "alembic.ini"))
    alembic.set_main_option("script_location", str(root / "migrations"))
    expected = ScriptDirectory.from_config(alembic).get_current_head()
    engine = create_engine(settings.database_url, pool_pre_ping=True)
    try:
        with engine.connect() as connection:
            installed = connection.execute(
                text("SELECT version_num FROM alembic_version")
            ).scalar_one_or_none()
        if installed != expected:
            raise RuntimeError(
                f"Database migration is {installed or 'missing'}; expected {expected}."
            )
    finally:
        engine.dispose()

    public_host = urlsplit(settings.public_url).hostname
    endpoints = {
        "Northstar Desk": (
            f"http://127.0.0.1:{settings.port}/api/health/ready",
            public_host,
        ),
    }
    deadline = time.monotonic() + timeout_seconds
    pending = dict(endpoints)
    last_errors: dict[str, str] = {}
    while pending and time.monotonic() < deadline:
        for name, (url, host_header) in list(pending.items()):
            try:
                request = internal_health_request(
                    url, f"https://{host_header}" if host_header else ""
                )
                with urllib.request.urlopen(request, timeout=2) as response:
                    if response.status == 200:
                        del pending[name]
                        continue
                    last_errors[name] = f"HTTP {response.status}"
            except Exception as exc:
                last_errors[name] = f"{type(exc).__name__}: {exc}"
        if pending:
            time.sleep(1)
    if pending:
        details = "; ".join(
            f"{name} ({last_errors.get(name, 'not ready')})" for name in pending
        )
        raise RuntimeError(f"Installed service readiness failed: {details}")
    try:
        with socket.create_connection(("127.0.0.1", settings.https_port), timeout=3):
            pass
    except OSError as exc:
        raise RuntimeError(
            f"Northstar HTTPS proxy is not listening on TCP {settings.https_port}: {exc}"
        ) from exc
    print("Northstar Desk and its HTTPS proxy are healthy.")


def main() -> int:
    parser = argparse.ArgumentParser(description="Northstar Desk packaged server")
    commands = parser.add_subparsers(dest="command", required=True)
    configure = commands.add_parser("configure-local")
    configure.add_argument("--data-root", type=Path, required=True)
    configure.add_argument("--organization", default="Northstar")
    configure.add_argument("--admin-email", default="admin@example.test")
    configure.add_argument("--port", type=int, default=8000)
    production = commands.add_parser("configure-production")
    production.add_argument("--data-root", type=Path, required=True)
    production.add_argument("--organization", required=True)
    production.add_argument("--admin-email", required=True)
    production.add_argument("--dns-name", required=True)
    production.add_argument("--asset-dns-name", default="assets.invalid")
    production.add_argument("--https-port", type=int, default=443)
    production.add_argument("--northstar-port", type=int, default=8000)
    production.add_argument("--assetpilot-port", type=int, default=5080)
    production.add_argument("--database-host", default="127.0.0.1")
    production.add_argument("--database-port", type=int, default=5432)
    production.add_argument("--database-name", default="northstar_desk")
    production.add_argument("--database-user", default="itsm_service")
    production.add_argument("--database-admin-user", default="postgres")
    admin_password_source = production.add_mutually_exclusive_group(required=True)
    admin_password_source.add_argument("--database-admin-password")
    admin_password_source.add_argument("--database-admin-password-file", type=Path)
    initial_admin_password_source = production.add_mutually_exclusive_group(required=True)
    initial_admin_password_source.add_argument("--initial-admin-password")
    initial_admin_password_source.add_argument("--initial-admin-password-file", type=Path)
    production.add_argument("--backup-directory", type=Path, required=True)
    production.add_argument("--source-config-file", type=Path)
    production.add_argument("--source-data-root", type=Path)
    production.add_argument("--restore-backup", type=Path)
    port_config = commands.add_parser("configure-ports")
    port_config.add_argument("--data-root", type=Path, required=True)
    port_config.add_argument("--https-port", type=int, required=True)
    port_config.add_argument("--northstar-port", type=int, required=True)
    port_config.add_argument("--assetpilot-port", type=int, default=5080)
    port_config.add_argument("--dns-name")
    port_config.add_argument("--asset-dns-name", default="assets.invalid")
    update_trust = commands.add_parser("configure-update-trust")
    update_trust.add_argument("--data-root", type=Path, required=True)
    update_trust.add_argument("--public-key-file", type=Path, required=True)
    migrate = commands.add_parser("migrate")
    migrate.add_argument("--data-root", type=Path, required=True)
    backup = commands.add_parser("backup")
    backup.add_argument("--data-root", type=Path, required=True)
    export_migration = commands.add_parser("export-migration")
    export_migration.add_argument("--data-root", type=Path, required=True)
    export_migration.add_argument("--output", type=Path, required=True)
    export_migration.add_argument("--backup-path", type=Path)
    import_migration = commands.add_parser("import-migration")
    import_migration.add_argument("--data-root", type=Path, required=True)
    import_migration.add_argument("--package", type=Path, required=True)
    import_migration.add_argument("--confirm", required=True)
    readiness = commands.add_parser("wait-ready")
    readiness.add_argument("--data-root", type=Path, required=True)
    readiness.add_argument("--timeout", type=int, default=120)
    port_check = commands.add_parser("check-ports")
    port_check.add_argument("--data-root", type=Path, required=True)
    port_check.add_argument("--https-port", type=int, required=True)
    port_check.add_argument("--northstar-port", type=int, required=True)
    run = commands.add_parser("serve")
    run.add_argument("--data-root", type=Path, required=True)
    run.add_argument("--open-browser", action="store_true")
    args = parser.parse_args()
    # Commands may change the process working directory while activating the
    # selected data root. Resolve every CLI path first so relative paths cannot
    # later point at a different configuration or database.
    for argument, value in vars(args).items():
        if isinstance(value, Path):
            setattr(args, argument, value.resolve())
    if args.command == "configure-local":
        if not 1024 <= args.port <= 65535:
            parser.error("port must be between 1024 and 65535")
        write_local_config(args.data_root, args.organization, args.port)
        initialize(args.data_root, args.organization, args.admin_email)
        print("Northstar Desk local evaluation configured successfully.")
        return 0
    if args.command == "configure-update-trust":
        configure_update_trust(args.data_root, args.public_key_file)
        print("Northstar Desk update verification trust configured successfully.")
        return 0
    if args.command == "backup":
        backup_existing_database(args.data_root)
        return 0
    if args.command == "export-migration":
        export_migration_package(args.data_root, args.output, args.backup_path)
        return 0
    if args.command == "import-migration":
        if args.confirm != "IMPORT":
            raise RuntimeError("Migration import refused; --confirm must be exactly IMPORT")
        import_migration_package(args.data_root, args.package)
        return 0
    if args.command == "configure-ports":
        try:
            configure_service_ports(
                args.data_root, args.https_port, args.northstar_port, args.assetpilot_port,
                args.dns_name, args.asset_dns_name,
            )
        except ValueError as exc:
            parser.error(str(exc))
        return 0
    if args.command == "check-ports":
        try:
            check_required_ports(
                args.https_port, args.northstar_port,
            )
        except ValueError as exc:
            parser.error(str(exc))
        return 0
    if args.command == "migrate":
        initialize(args.data_root)
        print("Northstar Desk database migration completed successfully.")
        return 0
    if args.command == "wait-ready":
        if not 10 <= args.timeout <= 600:
            parser.error("timeout must be between 10 and 600 seconds")
        wait_for_installed_services(args.data_root, args.timeout)
        return 0
    if args.command == "configure-production":
        if not 1 <= args.database_port <= 65535:
            parser.error("database port must be between 1 and 65535")
        try:
            validate_service_ports(
                args.https_port, args.northstar_port, args.assetpilot_port,
            )
        except ValueError as exc:
            parser.error(str(exc))
        for label, value in (("database name", args.database_name), ("database user", args.database_user)):
            if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_-]{0,62}", value):
                parser.error(f"{label} must start with a letter or underscore and contain only letters, numbers, underscores, or hyphens")
        admin_password = args.database_admin_password
        if args.database_admin_password_file:
            admin_password = args.database_admin_password_file.read_text(encoding="utf-8").rstrip("\r\n")
        if not admin_password:
            parser.error("PostgreSQL administrator password must not be empty")
        initial_admin_password = args.initial_admin_password
        if args.initial_admin_password_file:
            initial_admin_password = args.initial_admin_password_file.read_text(encoding="utf-8").rstrip("\r\n")
        if not initial_admin_password:
            parser.error("Initial Northstar administrator password must not be empty")
        if args.restore_backup and not args.source_config_file:
            parser.error("--source-config-file is required when --restore-backup is used so encrypted integration credentials remain readable")
        database_password = provision_postgresql(
            args.database_host,
            args.database_port,
            args.database_name,
            args.database_user,
            args.database_admin_user,
            admin_password,
        )
        write_production_config(
            args.data_root,
            args.organization,
            args.dns_name,
            args.asset_dns_name,
            args.database_host,
            args.database_port,
            args.database_name,
            args.database_user,
            database_password,
            args.backup_directory,
            args.https_port,
            args.northstar_port,
            args.assetpilot_port,
            args.source_config_file,
        )
        try:
            if args.restore_backup:
                restore_configured_backup(args.data_root, args.restore_backup)
                if args.source_data_root:
                    copy_restored_data_files(args.source_data_root, args.data_root)
                initialize(args.data_root)
            else:
                initialize(
                    args.data_root, args.organization, args.admin_email,
                    initial_admin_password,
                )
        except Exception:
            # Never leave a configuration containing a database password after a
            # failed prerequisite/connection test.
            config_path(args.data_root).unlink(missing_ok=True)
            raise
        protect_production_secrets(args.data_root)
        print("Northstar Desk production server configured successfully.")
        return 0
    serve(args.data_root, args.open_browser)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except SystemExit:
        raise
    except Exception:
        details = traceback.format_exc()
        try:
            data_root_index = sys.argv.index("--data-root") + 1
            diagnostic_root = Path(sys.argv[data_root_index]).resolve()
            diagnostic_root.mkdir(parents=True, exist_ok=True)
            (diagnostic_root / "setup-error.log").write_text(details, encoding="utf-8")
        except Exception:
            pass
        print(details, file=sys.stderr)
        raise SystemExit(1)
